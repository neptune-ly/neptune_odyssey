#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseRegisteredSurface, replaceGeneratedBlock } from "./lib/component-surface.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const contract = JSON.parse(
  fs.readFileSync(path.join(root, "contracts/odyssey-component-contract.json"), "utf8"),
);
const surface = parseRegisteredSurface(root);
const byTag = new Map(contract.components.map((component) => [component.web.tag, component]));

for (const entry of surface) {
  const component = byTag.get(entry.tag);
  if (!component) throw new Error(`${entry.tag} is registered but absent from the component contract.`);
  for (const framework of ["react", "vue"]) {
    const platform = component.platforms?.[framework];
    if (platform?.status !== "typed-wrapper" || platform.symbol !== entry.className) {
      throw new Error(`${entry.tag}: ${framework} contract must map to ${entry.className}.`);
    }
  }
}

const lines = [
  "/** Typed thin wrappers — attributes pass straight through to the custom element. */",
  "// GENERATED by tools/generate-framework-wrappers.mjs from register.ts + component contract.",
  "// <odyssey-generated-wrappers>",
  ...surface.map(
    ({ tag, className }) =>
      `export const ${className} = passthrough("${tag}", "${className}");`,
  ),
  "// </odyssey-generated-wrappers>",
].join("\n");

const targets = [
  "packages/neptune_react_ui/src/index.tsx",
  "packages/neptune_vue_ui/src/index.ts",
];

let drift = false;
for (const relative of targets) {
  const target = path.join(root, relative);
  const current = fs.readFileSync(target, "utf8");
  const next = replaceGeneratedBlock(current, lines);
  if (next !== current) {
    drift = true;
    if (!check) fs.writeFileSync(target, next);
  }
}

if (check && drift) {
  console.error("Framework wrapper drift detected. Run: pnpm wrappers:generate");
  process.exit(1);
}
console.log(
  `Framework wrappers ${check ? "match" : "generated from"} ${surface.length} registered web tags.`,
);
